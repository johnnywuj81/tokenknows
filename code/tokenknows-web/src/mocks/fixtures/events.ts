// 以"今天"为锚点生成相对时间(可在运行时被覆盖)
function isoOffset(daysAgo: number, hour: number, minute: number): string {
  const d = new Date()
  d.setDate(d.getDate() - daysAgo)
  d.setHours(hour, minute, 0, 0)
  return d.toISOString()
}

